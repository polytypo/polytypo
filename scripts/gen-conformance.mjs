#!/usr/bin/env node
// Generates spec/CONFORMANCE.md (docs/ARCHITECTURE.md section 6.2) — never hand-written, so it
// can't drift from spec/fixtures/*.json (the case counts, computed here) or
// scripts/conformance-status.json (per-runtime status, hand-maintained by an operator who has
// observed that runtime's own CI green against the spec version it claims). This is the minimal
// version of the conformance matrix: docs/REPOSITORY_SPLIT_AND_SPEC_SYNC.md section 5's full
// design (machine-readable per-runtime reports, cross-repo dispatch, sigstore transparency log)
// remains deferred — there is no automated ingestion here, only this generator reading a
// hand-maintained status file.
import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SPEC = path.join(ROOT, "spec");

const specVersion = (await readFile(path.join(SPEC, "VERSION"), "utf8")).trim();

const fixtureFiles = (await readdir(path.join(SPEC, "fixtures"), { withFileTypes: true }))
  .filter((e) => e.isFile() && e.name.endsWith(".json") && e.name !== "locale-resolution.json")
  .map((e) => e.name)
  .sort();

let casesTotal = 0;
for (const name of fixtureFiles) {
  const raw = JSON.parse(await readFile(path.join(SPEC, "fixtures", name), "utf8"));
  casesTotal += raw.cases.length;
}

const resolution = JSON.parse(
  await readFile(path.join(SPEC, "fixtures", "locale-resolution.json"), "utf8"),
);
const resolutionCases = resolution.cases.length;

const status = JSON.parse(
  await readFile(path.join(ROOT, "scripts", "conformance-status.json"), "utf8"),
);

const rows = status.runtimes
  .map((r) => {
    const conformant = r.conformant ? "✅ conformant" : "❌ not conformant";
    return `| [${r.name}](${r.repo}) | [package](${r.package}) | ${r.specVersion} | ${conformant} | ${r.lastVerified} |`;
  })
  .join("\n");

const notes = status.runtimes
  .filter((r) => r.notes)
  .map((r) => `- **${r.name}**: ${r.notes}`)
  .join("\n");

const body = `# Conformance matrix

Generated by \`scripts/gen-conformance.mjs\` from \`spec/fixtures/*.json\` and
\`scripts/conformance-status.json\` — do not hand-edit.

An implementation is polytypo **if and only if** it passes the full conformance suite for the
spec version it claims (docs/ARCHITECTURE.md section 6.2). The suite currently pinned to spec
version **${specVersion}**: **${casesTotal}** fixture cases across ${fixtureFiles.length} locale
files, plus **${resolutionCases}** locale-resolution cases.

| Runtime | Package | Spec version claimed | Status | Last verified |
| --- | --- | --- | --- | --- |
${rows}

"Last verified" is the date an operator last observed that runtime's own CI green against the
spec version it claims — not a live, automated signal. See
docs/REPOSITORY_SPLIT_AND_SPEC_SYNC.md section 5 for the deferred design that would make this
automated and independently attested.

"Conformant" is scoped to what a runtime actually claims to support (modes, dialects) — a runtime
that honestly declines an unsupported dialect with a stable error code is conformant for what it
claims, not partially broken. See the notes below for any runtime whose claimed scope is narrower
than the full spec.
${notes ? `\n${notes}\n` : ""}`;

await writeFile(path.join(SPEC, "CONFORMANCE.md"), body);
console.log("  spec/CONFORMANCE.md");
