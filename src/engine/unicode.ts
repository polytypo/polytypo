/** Simple uppercase mapping of one code point, or the code point itself when it has none. */
export function simpleUppercase(cp: number): number {
  for (let i = 0; i < SIMPLE_UPPERCASE.length; i += 4) {
    const start = SIMPLE_UPPERCASE[i] as number;
    if (cp < start) return cp;
    const end = SIMPLE_UPPERCASE[i + 1] as number;
    const step = SIMPLE_UPPERCASE[i + 2] as number;
    if (cp <= end && (cp - start) % step === 0) return cp + (SIMPLE_UPPERCASE[i + 3] as number);
  }
  return cp;
}
