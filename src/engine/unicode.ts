/** True for a code point in Lu or Lt. Binary search over UPPER_RANGES. */
export function isUpper(cp: number): boolean {
  if (cp < 0) return false;
  if (cp < 0x80) return cp >= 0x41 && cp <= 0x5a;
  let lo = 0;
  let hi = UPPER_RANGES.length / 2 - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const start = UPPER_RANGES[mid * 2] as number;
    const end = UPPER_RANGES[mid * 2 + 1] as number;
    if (cp < start) hi = mid - 1;
    else if (cp > end) lo = mid + 1;
    else return true;
  }
  return false;
}

