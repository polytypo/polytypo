// Shared Unicode general-category data for the rule engine.
//
// Unicode version: the table below is a DERIVED artifact, generated from the V8 UCD of the
// machine that produced it (Node 22.23.2 / Unicode 17.0, confirmed by
// tests/engine/unicode.test.ts, which re-checks every range boundary against the host
// runtime). The spec does not yet pin a UCD version — spec/UNICODE does not exist and
// spec/rules/apostrophe.md 7 and nbsp.md 7 both record the gap — so two runtimes built
// against different UCD releases can still disagree on newly assigned code points. The test
// turns that from a silent output change into a red build; the pin itself is a spec change.
//
// A table rather than `\p{L}`: RE2 (Go) has no Unicode property parity with PCRE, so a rule
// may not depend on the host regex engine (ARCHITECTURE.md 4.1).
//
// The table itself lives in ./letter-ranges.json, not inline, so that build tooling outside
// src/ (scripts/validate-spec.mjs, scripts/gen-locales.mjs — plain .mjs, run without a TS
// build step, so they cannot import this file directly) can read the identical data by
// re-parsing the same JSON rather than maintaining a second copy that could drift from this
// one. Both sides implement the same binary search independently; only the data is shared.

import letterRanges from "./letter-ranges.json" with { type: "json" };

/**
 * Unicode general categories Lu, Ll, Lt, Lm, Lo, Mn, Mc and Me as inclusive code-point
 * ranges, flattened to [start, end, start, end, ...] and sorted ascending.
 */
export const LETTER_RANGES: readonly number[] = letterRanges;

/** True for a code point in Lu, Ll, Lt, Lm, Lo, Mn, Mc or Me. Binary search over LETTER_RANGES. */
export function isLetter(cp: number): boolean {
  if (cp < 0) return false;
  if (cp < 0x80) return (cp >= 0x41 && cp <= 0x5a) || (cp >= 0x61 && cp <= 0x7a);
  let lo = 0;
  let hi = LETTER_RANGES.length / 2 - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const start = LETTER_RANGES[mid * 2] as number;
    const end = LETTER_RANGES[mid * 2 + 1] as number;
    if (cp < start) hi = mid - 1;
    else if (cp > end) lo = mid + 1;
    else return true;
  }
  return false;
}

